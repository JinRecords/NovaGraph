export type TranslationKey = keyof typeof dict.en;

const STORAGE_KEY = 'novagraph_locale';

let currentLocale: Locale = (localStorage.getItem(STORAGE_KEY) as Locale) === 'zh' ? 'zh' : 'en';
const listeners = new Set<(l: Locale) => void>();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale) {
  currentLocale = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {}
  listeners.forEach((fn) => fn(locale));
}

export function onLocaleChange(fn: (l: Locale) => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key: TranslationKey, locale: Locale = currentLocale): string {
  return dict[locale][key] ?? dict.en[key] ?? key;
}
